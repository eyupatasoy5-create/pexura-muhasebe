-- Pexura stok tutarliligi migrasyonu. Supabase SQL Editor'de bir kez calistirilir.
alter table public.urunler add column if not exists toplam_stok numeric;

update public.urunler u
set toplam_stok = greatest(0, coalesce(u.stok_miktar,0) + coalesce(x.satilan,0) - coalesce(x.iade,0))
from (
  select k.urun_id,
    sum(case when lower(coalesce(f.tip,'satis'))='iade' then 0 else coalesce(k.miktar,0) end) satilan,
    sum(case when lower(coalesce(f.tip,'satis'))='iade' then coalesce(k.miktar,0) else 0 end) iade
  from public.fatura_kalemler k join public.faturalar f on f.id=k.fatura_id group by k.urun_id
) x where x.urun_id=u.id and u.toplam_stok is null;
update public.urunler set toplam_stok=coalesce(stok_miktar,0) where toplam_stok is null;
alter table public.urunler alter column toplam_stok set default 0;

create or replace function public.adjust_stock_transaction(p_product_id uuid,p_mode text,p_quantity numeric,p_reason text,p_note text default null)
returns numeric language plpgsql security invoker set search_path=public as $$
declare v_old numeric; v_new numeric; v_delta numeric;
begin
  if p_mode not in ('giris','cikis','sayim') then raise exception 'Gecersiz stok islem turu'; end if;
  if p_quantity is null or p_quantity<0 then raise exception 'Miktar negatif olamaz'; end if;
  if p_mode<>'sayim' and p_quantity=0 then raise exception 'Miktar sifirdan buyuk olmali'; end if;
  if nullif(btrim(coalesce(p_reason,'')),'') is null then raise exception 'Stok hareketi nedeni zorunludur'; end if;
  select coalesce(stok_miktar,0) into v_old from public.urunler where id=p_product_id for update;
  if not found then raise exception 'Urun bulunamadi'; end if;
  v_new:=case p_mode when 'giris' then v_old+p_quantity when 'cikis' then v_old-p_quantity else p_quantity end;
  if v_new<0 then raise exception 'Stok eksiye dusmez. Mevcut: %, istenen cikis: %',v_old,p_quantity; end if;
  v_delta:=v_new-v_old;
  update public.urunler set stok_miktar=v_new,toplam_stok=greatest(0,coalesce(toplam_stok,v_old)+v_delta) where id=p_product_id;
  insert into public.stok_hareketleri(urun_id,miktar_degisim,tur,kaynak,kaynak_id,aciklama,user_id)
  values(p_product_id,v_delta,p_mode,'manuel',p_product_id,concat(p_reason,case when nullif(btrim(coalesce(p_note,'')),'') is not null then ' - '||btrim(p_note) else '' end),auth.uid());
  return v_new;
end; $$;

create or replace function public.batch_adjust_stock_transaction(p_items jsonb,p_reason text,p_note text default null)
returns jsonb language plpgsql security invoker set search_path=public as $$
declare v_item jsonb; v_results jsonb:='[]'::jsonb; v_stock numeric;
begin
  if jsonb_typeof(p_items)<>'array' or jsonb_array_length(p_items)=0 then raise exception 'Stok satiri bulunamadi'; end if;
  for v_item in select value from jsonb_array_elements(p_items) loop
    v_stock:=public.adjust_stock_transaction((v_item->>'product_id')::uuid,v_item->>'mode',(v_item->>'quantity')::numeric,p_reason,p_note);
    v_results:=v_results||jsonb_build_object('product_id',v_item->>'product_id','new_stock',v_stock);
  end loop;
  return v_results;
end; $$;

grant execute on function public.adjust_stock_transaction(uuid,text,numeric,text,text) to authenticated;
grant execute on function public.batch_adjust_stock_transaction(jsonb,text,text) to authenticated;

