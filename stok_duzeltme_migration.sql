create table if not exists public.inventory_daily_snapshots(
  snapshot_date date not null, product_id uuid not null references public.urunler(id) on delete cascade,
  stock_quantity numeric not null, unit_cost numeric not null, currency text not null,
  stock_value numeric not null, created_at timestamptz not null default now(),
  primary key(snapshot_date,product_id)
);
create or replace function public.take_inventory_snapshot() returns integer language plpgsql security definer set search_path=public as $$
declare n integer;
begin
  insert into public.inventory_daily_snapshots(snapshot_date,product_id,stock_quantity,unit_cost,currency,stock_value)
  select current_date,id,coalesce(stok_miktar,0),coalesce(alis_fiyat,0),coalesce(para_birimi,'USD'),round(coalesce(stok_miktar,0)*coalesce(alis_fiyat,0),2) from public.urunler
  on conflict(snapshot_date,product_id) do update set stock_quantity=excluded.stock_quantity,unit_cost=excluded.unit_cost,currency=excluded.currency,stock_value=excluded.stock_value,created_at=now();
  get diagnostics n=row_count; return n;
end; $$;

create extension if not exists pg_cron with schema pg_catalog;
do $$ begin
  if not exists(select 1 from cron.job where jobname='pexura-daily-inventory-snapshot') then
    perform cron.schedule('pexura-daily-inventory-snapshot','5 0 * * *','select public.take_inventory_snapshot();');
  end if;
end $$;

create or replace function public.delete_invoice_transaction(p_invoice_id uuid) returns boolean language plpgsql security invoker set search_path=public as $$
declare v_tip text; r record; v_delta numeric; v_new numeric;
begin
  select lower(coalesce(tip,'satis')) into v_tip from public.faturalar where id=p_invoice_id for update;
  if not found then raise exception 'Fatura bulunamadi'; end if;
  for r in select * from public.fatura_kalemler where fatura_id=p_invoice_id loop
    v_delta:=case when v_tip='iade' then -coalesce(r.miktar,0) else coalesce(r.miktar,0) end;
    update public.urunler set stok_miktar=coalesce(stok_miktar,0)+v_delta where id=r.urun_id returning stok_miktar into v_new;
    if v_new<0 then raise exception 'Fatura silme stogu eksiye dusuruyor'; end if;
    insert into public.stok_hareketleri(urun_id,miktar_degisim,tur,kaynak,kaynak_id,aciklama,user_id)
    values(r.urun_id,v_delta,'silme','fatura',p_invoice_id,'Fatura silindi geri alım',auth.uid());
  end loop;
  delete from public.fatura_kalemler where fatura_id=p_invoice_id;
  delete from public.faturalar where id=p_invoice_id;
  return true;
end; $$;
grant execute on function public.delete_invoice_transaction(uuid) to authenticated;
